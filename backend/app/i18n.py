"""Server messages in the reader's language: errors, and notifications.

Errors: `fail(key, status, **values)` raises with an `M` message. `M` is a
str holding the English text (so code and tests that compare details keep
working); the app's exception handlers render it at response time in the
request's language: the signed-in user's `language`, else `Accept-Language`.
Staff paths (/ops/, /mobile-admin/) always answer in English.

Notifications are rendered in the recipient's language when created, so
the inbox and the push match (see notifications.notify).
"""
from __future__ import annotations

from contextvars import ContextVar

from fastapi import HTTPException

LANGUAGES = ('en', 'sw')
STAFF_PATHS = ('/ops/', '/mobile-admin/')
# One mutable box per request. Sync dependencies run in worker threads with a
# copy of the context; the copy still points at this box, so a language the
# auth dependency records is seen by the exception handlers.
_request: ContextVar[dict | None] = ContextVar('omoterra_language', default=None)


def t(key, lang='en', **values):
    """The message for `key` in `lang`; English when either is missing."""
    lang = lang if lang in CATALOGUES else 'en'
    template = SW.get(key) if lang == 'sw' else None
    template = template or EN.get(key, key)
    try:
        return template.format(**{k: render(v, lang) for k, v in values.items()})
    except (KeyError, IndexError, ValueError):
        return template


def render(value, lang=None):
    """A value in `lang` (default: the request's): messages are translated,
    lists joined, anything else is text."""
    lang = lang or current()
    if isinstance(value, M):
        return t(value.key, lang, **value.values)
    if isinstance(value, (list, tuple)):
        return ', '.join(render(v, lang) for v in value)
    return '' if value is None else str(value)


class M(str):
    """A catalogue message. As a str it is the English text."""
    def __new__(cls, key, **values):
        self = super().__new__(cls, t(key, 'en', **values))
        self.key, self.values = key, values
        return self


def category(value):
    return M(f'category.{value}')


def error(key, status=409, **values):
    return HTTPException(status, detail=M(key, **values))


def fail(key, status=409, **values):
    raise error(key, status, **values)


def parse(header):
    """First supported language in an Accept-Language header, e.g. 'sw-TZ,en;q=0.8'."""
    for part in (header or '').split(','):
        code = part.split(';')[0].strip().lower().split('-')[0]
        if code in LANGUAGES:
            return code
    return None


def current():
    box = _request.get()
    return (box and (box['user'] or box['header'])) or 'en'


def use_user_language(lang):
    """Called once the request's user is known; their saved choice wins."""
    box = _request.get()
    if box is not None and not box['staff'] and lang in LANGUAGES:
        box['user'] = lang


class LanguageMiddleware:
    def __init__(self, app):
        self.app = app

    async def __call__(self, scope, receive, send):
        if scope['type'] != 'http':
            return await self.app(scope, receive, send)
        staff = any(p in scope['path'] for p in STAFF_PATHS)
        header = next((v.decode('latin-1') for k, v in scope['headers'] if k == b'accept-language'), '')
        token = _request.set({'staff': staff, 'user': None, 'header': 'en' if staff else parse(header)})
        try:
            await self.app(scope, receive, send)
        finally:
            _request.reset(token)


